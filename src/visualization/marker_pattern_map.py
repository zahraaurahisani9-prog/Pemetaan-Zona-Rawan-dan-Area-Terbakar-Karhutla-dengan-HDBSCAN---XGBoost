def load_visualization_data():
    """
    Load HDBSCAN outputs and prepare spatial visualization dataset.

    Returns
    -------
    tuple
        clustered_gdf : GeoDataFrame
        cluster_profile : DataFrame
        cluster_interpretation : DataFrame
    """

    logger.info("=" * 80)
    logger.info("LOADING VISUALIZATION DATA")
    logger.info("=" * 80)

    # -------------------------------------------------------------------------
    # Check Input Files
    # -------------------------------------------------------------------------

    input_files = [
        CLUSTERED_DATASET_FILE,
        CLUSTER_INTERPRETATION_FILE,
        CLUSTER_PROFILE_FILE,
    ]

    for file in input_files:

        if not file.exists():

            raise FileNotFoundError(
                f"Required file not found:\n{file}"
            )

        logger.info("Found : %s", file.name)

    # -------------------------------------------------------------------------
    # Read CSV Files
    # -------------------------------------------------------------------------

    clustered_dataset = pd.read_csv(
        CLUSTERED_DATASET_FILE
    )

    cluster_profile = pd.read_csv(
        CLUSTER_PROFILE_FILE
    )

    cluster_interpretation = pd.read_csv(
        CLUSTER_INTERPRETATION_FILE
    )

    logger.info(
        "Clustered Dataset : %d records",
        len(clustered_dataset),
    )

    logger.info(
        "Cluster Profile : %d clusters",
        len(cluster_profile),
    )

    logger.info(
        "Cluster Interpretation : %d clusters",
        len(cluster_interpretation),
    )

    # -------------------------------------------------------------------------
    # Merge Interpretation
    # -------------------------------------------------------------------------

    logger.info(
        "Merging clustered dataset with interpretation..."
    )

    clustered_dataset = clustered_dataset.merge(
        cluster_interpretation,
        on="Cluster",
        how="left",
        validate="many_to_one",
    )

    missing = clustered_dataset["Risk_Level"].isna().sum()

    if missing > 0:

        logger.warning(
            "%d pixels have no interpretation.",
            missing,
        )

    else:

        logger.info(
            "All pixels successfully merged."
        )

    # -------------------------------------------------------------------------
    # Create GeoDataFrame
    # -------------------------------------------------------------------------

    logger.info(
        "Creating GeoDataFrame..."
    )

    clustered_gdf = gpd.GeoDataFrame(
        clustered_dataset,
        geometry=gpd.points_from_xy(
            clustered_dataset["longitude"],
            clustered_dataset["latitude"],
        ),
        crs="EPSG:4326",
    )

    logger.info(
        "GeoDataFrame created successfully."
    )

    logger.info(
        "Coordinate Reference System : %s",
        clustered_gdf.crs,
    )

    # -------------------------------------------------------------------------
    # Dataset Summary
    # -------------------------------------------------------------------------

    logger.info("-" * 80)

    logger.info(
        "Total Pixels : %d",
        len(clustered_gdf),
    )

    logger.info(
        "Unique Clusters : %d",
        clustered_gdf["Cluster"].nunique(),
    )

    logger.info(
        "Risk Levels : %s",
        ", ".join(
            clustered_gdf["Risk_Level"]
            .dropna()
            .unique()
            .tolist()
        ),
    )

    logger.info("-" * 80)

    return (
        clustered_gdf,
        cluster_profile,
        cluster_interpretation,
    )

