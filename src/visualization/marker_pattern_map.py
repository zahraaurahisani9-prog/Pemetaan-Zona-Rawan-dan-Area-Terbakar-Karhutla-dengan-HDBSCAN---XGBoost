# ADAPTIVE MARKER OFFSET
# =============================================================================
def apply_marker_offset(
    subset,
    radius=0.00015,
):
    """
    Apply deterministic circular offsets for overlapping markers.

    The original hotspot coordinates remain unchanged.
    Only marker positions during plotting are shifted.
    """

    if len(subset) <= 1:

        return (
            subset.geometry.x.to_numpy(),
            subset.geometry.y.to_numpy(),
        )

    x = subset.geometry.x.to_numpy(dtype=float)

    y = subset.geometry.y.to_numpy(dtype=float)

    x_plot = x.copy()

    y_plot = y.copy()

    processed = np.zeros(
        len(subset),
        dtype=bool,
    )

    tolerance = radius * 0.50

    for i in range(len(subset)):

        if processed[i]:

            continue

        dx = x - x[i]

        dy = y - y[i]

        distance = np.sqrt(
            dx ** 2 + dy ** 2
        )

        neighbours = np.where(
            distance < tolerance
        )[0]

        if len(neighbours) == 1:

            processed[i] = True

            continue

        angles = np.linspace(
            0,
            2 * np.pi,
            len(neighbours),
            endpoint=False,
        )

        for idx, angle in zip(
            neighbours,
            angles,
        ):

            x_plot[idx] += (
                radius * np.cos(angle)
            )

            y_plot[idx] += (
                radius * np.sin(angle)
            )

            processed[idx] = True

    return (
        x_plot,
        y_plot,
    )

