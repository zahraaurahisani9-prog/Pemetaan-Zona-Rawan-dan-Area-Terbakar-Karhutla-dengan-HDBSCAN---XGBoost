# CREATE BASE MAP
# =============================================================================

def create_base_map(
    boundary: gpd.GeoDataFrame,
):
    """
    Create standardized map canvas.

    Parameters
    ----------
    boundary : GeoDataFrame

    Returns
    -------
    tuple
        fig, ax
    """

    fig, ax = plt.subplots(
        figsize=FIGSIZE,
    )

    boundary.plot(
        ax=ax,
        facecolor="whitesmoke",
        edgecolor=BOUNDARY_COLOR,
        linewidth=BOUNDARY_WIDTH,
        zorder=1,
    )

    ax.set_xlabel("Longitude")

    ax.set_ylabel("Latitude")

    ax.set_aspect("equal")

    
    ax.grid(

    color="gray",

    linestyle=":",

    linewidth=0.5,

    alpha=0.35,

    )

    return fig, ax

