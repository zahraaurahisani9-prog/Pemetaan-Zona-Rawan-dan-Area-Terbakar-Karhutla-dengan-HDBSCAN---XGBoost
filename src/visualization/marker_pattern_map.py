def create_wildfire_risk_map(
    clustered_gdf,
    boundary,
):
    """
    Create wildfire risk map using interpreted HDBSCAN clusters.

    Marker positions are visually adjusted to reduce overlap while
    preserving the original hotspot coordinates.
    """

    logger.info("=" * 80)
    logger.info("CREATING WILDFIRE RISK MAP")
    logger.info("=" * 80)

    # -------------------------------------------------------------------------
    # Create Base Map
    # -------------------------------------------------------------------------

    fig, ax = create_base_map(
        boundary
    )

    # -------------------------------------------------------------------------
    # Risk Drawing Order
    # -------------------------------------------------------------------------

    risk_order = [

        "Very High",

        "High",

        "Moderate",

        "Low",

        "Very Low",

        "Noise",

    ]

    # -------------------------------------------------------------------------
    # Legend Container
    # -------------------------------------------------------------------------

    legend_handles = []

    # -------------------------------------------------------------------------
    # Draw Every Risk Level
    # -------------------------------------------------------------------------

    for risk in risk_order:

        subset = clustered_gdf[
            clustered_gdf["Risk_Level"] == risk
        ]

        if subset.empty:

            continue

        # -------------------------------------------------------------
        # Plot Marker
        # -------------------------------------------------------------

        plot_risk_markers(

            ax=ax,

            subset=subset,

            risk=risk,

        )

        # -------------------------------------------------------------
        # Legend
        # -------------------------------------------------------------

        legend_handles.append(

            Line2D(

                [],

                [],

                linestyle="",

                marker=RISK_MARKER[risk],

                markerfacecolor=RISK_COLOR[risk],

                markeredgecolor=RISK_EDGE_COLOR,

                markeredgewidth=RISK_EDGE_WIDTH,

                markersize=np.sqrt(
                    RISK_MARKER_SIZE[risk]
                ),

                label=risk,

            )

        )

        ax.set_title(
        (
            "Wildfire Risk Level Map\n"
            "Kabupaten Ketapang (2025–2026)"
        ),
        fontsize=16,
        fontweight="bold",
        pad=15,
    )

    add_north_arrow(ax)

    add_footer(fig)

    ax.legend(
        handles=legend_handles,
        title="Risk Level",
        loc="lower left",
        frameon=True,
    )

    output = MAP_OUTPUT_DIR / "04_wildfire_risk_map.png"

    plt.savefig(
        output,
        dpi=DPI,
        bbox_inches="tight",
        pad_inches=0.25,
    )

    logger.info(
        "Saved : %s",
        output.name,
    )

    plt.close(fig)

       
