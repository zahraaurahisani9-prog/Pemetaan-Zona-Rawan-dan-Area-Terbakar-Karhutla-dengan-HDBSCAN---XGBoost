# PLOT RISK MARKERS
# =============================================================================
def plot_risk_markers(
    ax,
    subset,
    risk,
):
    """
    Plot wildfire hotspot markers.
    """

    if subset.empty:

        return

    if risk not in RISK_MARKER:

        raise ValueError(
            f"Unknown Risk Level : {risk}"
        )

    x_plot, y_plot = apply_marker_offset(
        subset
    )

    ax.scatter(

        x_plot,

        y_plot,

        marker=RISK_MARKER[risk],

        s=RISK_MARKER_SIZE[risk],

        c=RISK_COLOR[risk],

        edgecolors=RISK_EDGE_COLOR,

        linewidths=RISK_EDGE_WIDTH,

        alpha=RISK_ALPHA,

        zorder=RISK_ZORDER[risk],

    )

