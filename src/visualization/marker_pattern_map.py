# CLUSTER STATISTICS
# =============================================================================

def create_cluster_statistics(
    cluster_summary,
    cluster_interpretation,
):
    """
    Create statistical summary of HDBSCAN clusters.
    """

    logger.info("=" * 80)
    logger.info("CREATING CLUSTER STATISTICS")
    logger.info("=" * 80)

    fig, axes = plt.subplots(
        1,
        3,
        figsize=(18,6),
    )

    # -------------------------------------------------------------------------
    # Cluster Distribution
    # -------------------------------------------------------------------------
    profile = (
        cluster_summary[
            cluster_summary["Activity_Rank"].notna()
        ]
        .copy()
        .sort_values("Activity_Rank")
    )

    profile = (
    cluster_summary[
        cluster_summary["Activity_Rank"].notna()
    ]
    .copy()
    .sort_values("Activity_Rank")
    )

    axes[0].bar(
        profile["Cluster"].astype(str),
        profile["Pixel_Count"],
    )

    axes[0].set_title(
        "Cluster Distribution"
    )

    axes[0].set_xlabel(
        "Cluster"
    )

    axes[0].set_ylabel(
        "Pixels"
    )

    # -------------------------------------------------------------------------
    # Risk Distribution
    # -------------------------------------------------------------------------

    risk_order = [
        "Very High",
        "High",
        "Moderate",
        "Low",
        "Very Low",
        "Noise",
    ]

    risk = (
        cluster_interpretation
        .groupby("Risk_Level")
        .size()
        .reindex(
            risk_order,
            fill_value=0,
        )
    )

    axes[1].bar(
        risk.index,
        risk.values,
    )

    axes[1].set_title(
        "Risk Level Distribution"
    )

    axes[1].tick_params(
        axis="x",
        rotation=45,
    )

    # -------------------------------------------------------------------------
    # FRP vs Hotspot
    # -------------------------------------------------------------------------

    axes[2].scatter(
        cluster_summary[
            "Mean_Hotspot_Frequency"
        ],
        cluster_summary[
            "Mean_FRP_Max"
        ],
        s=70,
    )

    axes[2].set_title(
        "FRP vs Hotspot"
    )

    axes[2].set_xlabel(
        "Mean Hotspot Frequency"
    )

    axes[2].set_ylabel(
        "Mean FRP"
    )

    plt.tight_layout()

    output = (
        VIS_OUTPUT_DIR
        / "05_cluster_statistics.png"
    )

    plt.savefig(
        output,
        dpi=DPI,
        bbox_inches="tight",
    )

    logger.info(
        "Saved : %s",
        output.name,
    )

    plt.close(fig)

