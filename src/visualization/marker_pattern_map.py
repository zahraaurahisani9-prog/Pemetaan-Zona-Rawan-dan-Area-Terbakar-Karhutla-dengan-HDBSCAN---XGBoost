def load_administrative_boundary():
    """
    Load Ketapang administrative boundary.

    Returns
    -------
    GeoDataFrame
        Administrative boundary.
    """

    logger.info("=" * 80)
    logger.info("LOADING ADMINISTRATIVE BOUNDARY")
    logger.info("=" * 80)

    if not SHAPEFILE_PATH.exists():

        raise FileNotFoundError(
            f"Shapefile not found:\n{SHAPEFILE_PATH}"
        )

    boundary = gpd.read_file(
        SHAPEFILE_PATH
    )

    if boundary.crs != "EPSG:4326":

        logger.info(
            "Reprojecting boundary to EPSG:4326..."
        )

        boundary = boundary.to_crs(
            "EPSG:4326"
        )

    logger.info(
        "Boundary loaded successfully."
    )

    logger.info(
        "Total polygons : %d",
        len(boundary),
    )

    logger.info(
        "CRS : %s",
        boundary.crs,
    )

    logger.info(
        "Boundary extent:"
    )

    logger.info(
        "MinX : %.6f",
        boundary.total_bounds[0],
    )

    logger.info(
        "MinY : %.6f",
        boundary.total_bounds[1],
    )

    logger.info(
        "MaxX : %.6f",
        boundary.total_bounds[2],
    )

    logger.info(
        "MaxY : %.6f",
        boundary.total_bounds[3],
    )

    return boundary

